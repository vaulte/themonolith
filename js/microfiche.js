/* =========================================
   BUILD FRAME LIST
========================================= */

function buildFrameList() {

    frameList.innerHTML = "";

    archive.forEach((item, index) => {

        const element = document.createElement("div");

        element.className = "frame-item";

        element.innerHTML = `
            <div class="frame-number">
                FRAME ${item.frame}
            </div>

            <div class="frame-title">
                ${item.title}
            </div>
        `;

        element.onclick = function() {
            loadFrame(index);
        };

        frameList.appendChild(element);

    });

}


/* =========================================
   LOAD FRAME
========================================= */

function loadFrame(index, updateHash = true) {

    if (index < 0) {
        index = 0;
    }

    if (index >= archive.length) {
        index = archive.length - 1;
    }

    currentIndex = index;

    const item = archive[currentIndex];

    scan.innerHTML = item.content;

    scan.style.transform =
        `scale(${zoom}) rotate(${rotation}deg)`;

    frameCounter.textContent =
        `FRAME ${item.frame} / ${archive[archive.length - 1].frame}`;

    infoFrame.textContent = item.frame;

    infoType.textContent = item.type;

    infoClassification.textContent =
        item.classification;

    infoSource.textContent =
        item.source;

    frameInput.value = item.frame;

    previousButton.disabled =
        currentIndex === 0;

    nextButton.disabled =
        currentIndex === archive.length - 1;


    document.querySelectorAll(".frame-item")
        .forEach((element, i) => {

            element.classList.toggle(
                "active",
                i === currentIndex
            );

        });


    if (updateHash) {

        history.replaceState(
            null,
            "",
            "#" + item.frame
        );

    }

}


/* =========================================
   NEXT / PREVIOUS
========================================= */

function nextFrame() {

    if (currentIndex < archive.length - 1) {

        loadFrame(currentIndex + 1);

    }

}


function previousFrame() {

    if (currentIndex > 0) {

        loadFrame(currentIndex - 1);

    }

}


/* =========================================
   JUMP TO FRAME
========================================= */

function jumpToFrame() {

    const value =
        frameInput.value.trim();

    const index =
        archive.findIndex(
            item => item.frame === value
        );

    if (index !== -1) {

        loadFrame(index);

    } else {

        alert(
            "FRAME NOT FOUND\n\n" +
            "The requested frame is not available " +
            "in this archive."
        );

    }

}


/* =========================================
   ZOOM
========================================= */

function updateZoom() {

    scan.style.transform =
        `scale(${zoom}) rotate(${rotation}deg)`;

    zoomValue.textContent =
        Math.round(zoom * 100) + "%";

}


function zoomIn() {

    zoom += 0.1;

    if (zoom > 2) {
        zoom = 2;
    }

    updateZoom();

}


function zoomOut() {

    zoom -= 0.1;

    if (zoom < 0.5) {
        zoom = 0.5;
    }

    updateZoom();

}


function resetZoom() {

    zoom = 1;
    rotation = 0;

    updateZoom();

}


/* =========================================
   ROTATION
========================================= */

function rotateScan(direction) {

    rotation += direction;

    if (rotation > 3) {
        rotation = 0;
    }

    if (rotation < -3) {
        rotation = 0;
    }

    updateZoom();

}


/* =========================================
   KEYBOARD NAVIGATION
========================================= */

document.addEventListener(
    "keydown",
    function(event) {

        if (event.key === "ArrowRight") {

            nextFrame();

        }

        if (event.key === "ArrowLeft") {

            previousFrame();

        }

    }
);


/* =========================================
   HASH NAVIGATION
========================================= */

function loadHashFrame() {

    const hash =
        window.location.hash
            .replace("#", "")
            .trim();

    if (!hash) {

        loadFrame(0, false);

        return;

    }

    const index =
        archive.findIndex(
            item => item.frame === hash
        );

    if (index !== -1) {

        loadFrame(index, false);

    } else {

        loadFrame(0, false);

    }

}


/* =========================================
   INITIALIZE
========================================= */

buildFrameList();

loadHashFrame();

